package com.example.smarthome.ui.dialog;

/**
 * Результат команды управления для диалога.
 * Диалог после запуска команды показывает ожидание и закрывается только по onSuccess.
 * Вызывать методы нужно в главном потоке; если диалог уже закрыт, вызов игнорируется.
 */
public interface ControlResultCallback
{
    /** Оборудование подтвердило команду, состояние сохранено. */
    void onSuccess();

    /** Команда не подтверждена или не сохранена. Диалог остаётся открытым и показывает текст. */
    void onFailure(String message);
}
